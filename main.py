# 14. JSON 개별 패턴 분석
# ============================================================

def analyze_pattern_case(
    case_id: str,
    case_data: Any,
    filters: Dict[str, Any]
) -> Dict[str, Any]:
    """
    하나의 JSON 패턴 케이스를 분석한다.

    --------------------------------------------------------
    예:
    --------------------------------------------------------

    case_id:

        "size_5_0"

    case_data:

        {
            "input": [...],
            "expected": "Cross"
        }

    --------------------------------------------------------
    분석 순서
    --------------------------------------------------------

    1. case_id에서 크기 추출
    2. 지원하는 크기인지 확인
    3. input / expected 존재 여부 확인
    4. expected 라벨 정규화
    5. 패턴 행렬 검사
    6. Cross/X 필터 검사
    7. Cross MAC 계산
    8. X MAC 계산
    9. 두 점수 비교
    10. expected와 prediction 비교
    11. PASS / FAIL 결정
    """

    # 하나의 케이스에 대한 결과를 저장할 dictionary입니다.
    result = {
        "case_id": case_id,
        "status": "FAIL",
        "reason": "",
        "cross_score": None,
        "x_score": None,
        "prediction": None,
        "expected": None,
    }

    # --------------------------------------------------------
    # 1. case_id에서 크기 추출
    # --------------------------------------------------------

    size = extract_size_from_pattern_key(case_id)

    # key 형식이 잘못되면 실패 처리합니다.
    if size is None:
        result["reason"] = (
            "패턴 키 형식 오류: "
            "size_{N}_{idx} 형식이 필요합니다."
        )
        return result

    # --------------------------------------------------------
    # 2. 지원하는 크기인지 확인
    # --------------------------------------------------------

    if size not in SUPPORTED_JSON_SIZES:
        result["reason"] = (
            f"지원하지 않는 크기입니다: {size}x{size}"
        )
        return result

    # --------------------------------------------------------
    # 3. case_data가 객체인지 확인
    # --------------------------------------------------------

    if not isinstance(case_data, dict):
        result["reason"] = (
            "패턴 데이터가 객체가 아닙니다."
        )
        return result

    # input 필드가 있는지 확인합니다.
    if "input" not in case_data:
        result["reason"] = (
            "'input' 필드가 없습니다."
        )
        return result

    # expected 필드가 있는지 확인합니다.
    if "expected" not in case_data:
        result["reason"] = (
            "'expected' 필드가 없습니다."
        )
        return result

    # --------------------------------------------------------
    # 4. expected 라벨 정규화
    # --------------------------------------------------------

    expected = normalize_label(
        case_data["expected"]
    )

    # 알 수 없는 라벨이면 실패입니다.
    if expected is None:
        result["reason"] = (
            f"알 수 없는 expected 라벨: "
            f"{case_data['expected']!r}"
        )
        return result

    # 정상화된 expected 값을 결과에 저장합니다.
    result["expected"] = expected

    # --------------------------------------------------------
    # 5. 패턴 행렬 검사
    # --------------------------------------------------------

    pattern = case_data["input"]

    # 패턴이 정확히 size x size인지 검사합니다.
    ok, reason = validate_square_matrix(
        pattern,
        expected_size=size
    )

    # 패턴이 잘못되었으면 실패 처리합니다.
    if not ok:
        result["reason"] = (
            f"패턴 크기/데이터 오류: {reason}"
        )
        return result

    # 패턴의 모든 값을 float으로 변환합니다.
    pattern = to_float_matrix(pattern)

    # --------------------------------------------------------
    # 6. Cross/X 필터 검사
    # --------------------------------------------------------

    ok, reason, normalized_filters = (
        validate_filter_group(
            filters,
            size
        )
    )

    # 필터가 잘못되었다면 실패 처리합니다.
    if not ok:
        result["reason"] = (
            f"필터 오류: {reason}"
        )
        return result

    # 검증된 Cross 필터를 가져옵니다.
    cross_filter = normalized_filters["Cross"]

    # 검증된 X 필터를 가져옵니다.
    x_filter = normalized_filters["X"]

    # --------------------------------------------------------
    # 7. Cross MAC 계산
    # --------------------------------------------------------

    cross_score = mac_score(
        pattern,
        cross_filter
    )

    # --------------------------------------------------------
    # 8. X MAC 계산
    # --------------------------------------------------------

    x_score = mac_score(
        pattern,
        x_filter
    )

    # --------------------------------------------------------
    # 9. 두 점수 비교
    # --------------------------------------------------------
    #
    # JSON 모드에서는
    #
    # score_a = Cross 점수
    # score_b = X 점수
    #
    # label_a = Cross
    # label_b = X
    #
    # 로 사용합니다.

    prediction = classify_scores(
        cross_score,
        x_score,
        label_a="Cross",
        label_b="X",
        epsilon=EPSILON
    )

    # 계산 결과를 result에 저장합니다.
    result["cross_score"] = cross_score
    result["x_score"] = x_score
    result["prediction"] = prediction

    # --------------------------------------------------------
    # 10. expected와 prediction 비교
    # --------------------------------------------------------

    if prediction == expected:

        # 예상값과 실제 판정이 같으면 PASS입니다.
        result["status"] = "PASS"
        result["reason"] = "정상 판정"

    else:

        # 예상값과 실제 판정이 다르면 FAIL입니다.
        result["status"] = "FAIL"

        # 동점으로 판정된 경우에는 별도의 이유를 기록합니다.
        if prediction == "UNDECIDED":

            result["reason"] = (
                f"동점 규칙: "
                f"|Cross-X| < {EPSILON}"
            )

        else:

            # Cross/X 중 잘못된 결과가 나온 경우입니다.
            result["reason"] = (
                f"판정 불일치: "
                f"expected={expected}, "
                f"prediction={prediction}"
            )

    # 최종 분석 결과를 반환합니다.
    return result


