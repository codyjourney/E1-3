# ============================================================
# 9. MAC 성능 측정
# ============================================================

def measure_mac(
    pattern: List[List[float]],
    filter_matrix: List[List[float]],
    repeats: int = PERFORMANCE_REPEATS
) -> Tuple[float, float]:
    """
    MAC 연산만 반복 측정한다.

    --------------------------------------------------------
    반환값
    --------------------------------------------------------

    (
        평균 시간(ms),
        마지막 MAC 결과
    )

    예:

    (0.012345, 25.0)

    --------------------------------------------------------
    측정 방법
    --------------------------------------------------------

    1. Warm-up으로 MAC을 한 번 실행
    2. 실제 측정을 repeats번 수행
    3. 각 실행 시간을 리스트에 저장
    4. 평균 시간을 계산
    5. 평균 시간과 마지막 결과를 반환
    """

    # 반복 횟수가 1보다 작으면 측정할 수 없습니다.
    if repeats <= 0:
        raise ValueError("repeats는 1 이상이어야 합니다.")

    # 각 MAC 실행에 걸린 시간을 저장합니다.
    elapsed_times = []

    # 마지막 MAC 결과를 저장할 변수입니다.
    last_score = 0.0

    # --------------------------------------------------------
    # Warm-up
    # --------------------------------------------------------
    #
    # 실제 시간 측정 전에 한 번 실행합니다.
    #
    # 첫 실행에는 Python 실행 환경 등의 초기 비용이
    # 포함될 수 있기 때문에 별도로 먼저 실행합니다.
    last_score = mac_score(
        pattern,
        filter_matrix
    )

    # --------------------------------------------------------
    # 실제 측정
    # --------------------------------------------------------

    for _ in range(repeats):

        # 현재 시간을 기록합니다.
        start = time.perf_counter()

        # 실제 측정 대상인 MAC 연산입니다.
        last_score = mac_score(
            pattern,
            filter_matrix
        )

        # 연산이 끝난 시간을 기록합니다.
        end = time.perf_counter()

        # 초 단위의 차이를 밀리초(ms)로 변환합니다.
        #
        # 1초 = 1000ms
        elapsed_times.append(
            (end - start) * 1000.0
        )

    # 측정한 모든 시간의 평균을 계산합니다.
    average_ms = (
        sum(elapsed_times)
        / len(elapsed_times)
    )

    # 평균 시간과 마지막 MAC 결과를 반환합니다.
    return average_ms, last_score


