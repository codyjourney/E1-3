# 11. 사용자 입력 모드
# ============================================================

def read_matrix_from_console(
    size: int,
    matrix_name: str
) -> List[List[float]]:
    """
    콘솔에서 N×N 행렬을 한 줄씩 입력받는다.

    --------------------------------------------------------
    예:
    --------------------------------------------------------

    size = 3

    사용자 입력:

    0 1 0
    1 1 1
    0 1 0

    그러면 내부적으로:

    [
        [0.0, 1.0, 0.0],
        [1.0, 1.0, 1.0],
        [0.0, 1.0, 0.0]
    ]

    형태가 됩니다.

    --------------------------------------------------------
    잘못된 입력
    --------------------------------------------------------

    3개를 입력해야 하는데

    1 2

    처럼 2개만 입력하면 다시 입력을 요청합니다.

    숫자가 아닌 값을 입력해도 다시 입력을 요청합니다.
    """

    # 잘못된 행렬을 입력했을 경우
    # 전체 행렬을 처음부터 다시 입력받기 위해
    # while True를 사용합니다.
    while True:

        print(
            f"\n{matrix_name} "
            f"({size}줄 입력, 공백 구분)"
        )

        # 입력받은 행들을 저장할 리스트입니다.
        matrix = []

        # size개의 행을 입력받습니다.
        for row_index in range(size):

            # 한 행이 올바르게 입력될 때까지 반복합니다.
            while True:

                # 사용자에게 한 줄을 입력받습니다.
                text = input(
                    f"{row_index + 1}/{size}행 > "
                ).strip()

                # 공백을 기준으로 값을 분리합니다.
                #
                # "1 2 3"
                #
                # ->
                #
                # ["1", "2", "3"]
                parts = text.split()

                # 입력한 숫자의 개수가
                # 정확히 size개인지 검사합니다.
                if len(parts) != size:

                    print(
                        f"입력 형식 오류: "
                        f"각 줄에 {size}개의 숫자를 "
                        f"공백으로 구분해 입력하세요."
                    )

                    # 현재 행을 다시 입력받습니다.
                    continue

                try:

                    # 문자열을 float으로 변환합니다.
                    #
                    # "1" -> 1.0
                    # "2.5" -> 2.5
                    row = [
                        float(value)
                        for value in parts
                    ]

                except ValueError:

                    # 숫자로 변환할 수 없는 값이 있으면
                    # 현재 행을 다시 입력받습니다.
                    print(
                        "입력 형식 오류: 숫자만 입력하세요."
                    )
                    continue

                # 정상적으로 입력된 행을 matrix에 추가합니다.
                matrix.append(row)

                # 현재 행 입력을 종료하고
                # 다음 행으로 이동합니다.
                break

        # 모든 행을 입력받은 뒤
        # 다시 한번 정사각형 행렬인지 검증합니다.
        ok, reason = validate_square_matrix(
            matrix,
            expected_size=size
        )

        # 정상적인 행렬이면
        # 입력된 행렬을 반환합니다.
        if ok:
            return matrix

        # 여기까지 왔다면 행렬 전체 검증에 실패한 것입니다.
        print(f"입력 오류: {reason}")
        print("행렬을 처음부터 다시 입력해주세요.")


def run_user_mode() -> None:
    """
    모드 1을 실행한다.

    사용자 입력 모드에서는
    필터 A와 필터 B를 비교하므로
    최종 판정은 A / B로 표시한다.
    """

    # 사용자 입력 모드는 3x3만 사용합니다.
    size = 3

    # --------------------------------------------------------
    # [1] 필터 입력
    # --------------------------------------------------------

    print("\n#---------------------------------------")
    print("# [1] 필터 입력")
    print("#---------------------------------------")

    # 필터 A를 입력받습니다.
    filter_a = read_matrix_from_console(
        size,
        "필터 A"
    )

    # 필터 B를 입력받습니다.
    filter_b = read_matrix_from_console(
        size,
        "필터 B"
    )

    print("\n필터 A 저장 완료.")
    print("필터 B 저장 완료.")

    # --------------------------------------------------------
    # [2] 패턴 입력
    # --------------------------------------------------------

    print("\n#---------------------------------------")
    print("# [2] 패턴 입력")
    print("#---------------------------------------")

    # 패턴을 입력받습니다.
    pattern = read_matrix_from_console(
        size,
        "패턴"
    )

    print("\n패턴 저장 완료.")

    # --------------------------------------------------------
    # [3] MAC 결과
    # --------------------------------------------------------

    print("\n#---------------------------------------")
    print("# [3] MAC 결과")
    print("#---------------------------------------")

    # 패턴과 필터 A를 MAC 연산합니다.
    score_a = mac_score(
        pattern,
        filter_a
    )

    # 패턴과 필터 B를 MAC 연산합니다.
    score_b = mac_score(
        pattern,
        filter_b
    )

    # 필터 A에 대한 MAC 연산 시간을 측정합니다.
    average_a_ms, _ = measure_mac(
        pattern,
        filter_a,
        PERFORMANCE_REPEATS
    )

    # 필터 B에 대한 MAC 연산 시간을 측정합니다.
    average_b_ms, _ = measure_mac(
        pattern,
        filter_b,
        PERFORMANCE_REPEATS
    )

    # A와 B의 평균 연산 시간을 다시 평균냅니다.
    average_ms = (
        average_a_ms + average_b_ms
    ) / 2.0

    # --------------------------------------------------------
    # 사용자 입력 모드에서는 A/B로 판정
    # --------------------------------------------------------
    #
    # A 점수가 높으면 "A"
    # B 점수가 높으면 "B"
    # 거의 같으면 "UNDECIDED"
    #
    result = classify_scores(
        score_a,
        score_b,
        label_a="A",
        label_b="B",
        epsilon=EPSILON
    )

    # MAC 점수를 출력합니다.
    print(f"A 점수: {score_a:.10f}")
    print(f"B 점수: {score_b:.10f}")

    # 평균 연산 시간을 출력합니다.
    print(
        f"연산 시간(평균/{PERFORMANCE_REPEATS}회): "
        f"{average_ms:.6f} ms"
    )

    # 동점인 경우 사용자에게 알아보기 쉬운 문장으로 출력합니다.
    if result == "UNDECIDED":

        print(
            f"판정: 판정 불가 "
            f"(|A-B| < {EPSILON})"
        )

    else:

        # A 또는 B를 출력합니다.
        print(f"판정: {result}")

    # --------------------------------------------------------
    # [4] 성능 분석
    # --------------------------------------------------------

    print("\n#---------------------------------------")
    print("# [4] 성능 분석")
    print("#---------------------------------------")

    # 사용자 입력 모드에서는 3×3만 측정합니다.
    #
    # 성능 측정에서는 실제 Cross/X 형태의
    # 필터를 각각 생성합니다.
    run_performance_analysis(
        (3,),
        PERFORMANCE_REPEATS
    )


