# 1. 라벨 정규화(Label Normalization)
# ============================================================

def normalize_label(label: Any) -> Optional[str]:
    """
    입력받은 라벨을 프로그램 내부에서 사용하는
    표준 라벨로 변환한다.

    --------------------------------------------------------
    입력 예시
    --------------------------------------------------------

    "+"
        -> "Cross"

    "cross"
        -> "Cross"

    "Cross"
        -> "Cross"

    "x"
        -> "X"

    "X"
        -> "X"

    --------------------------------------------------------
    알 수 없는 값
    --------------------------------------------------------

    "circle"
    123
    None

    등은 인식할 수 없으므로 None을 반환한다.

    --------------------------------------------------------
    왜 필요한가?
    --------------------------------------------------------

    JSON에서는 라벨이
    "+", "cross", "Cross" 등 여러 형태로 들어올 수 있습니다.

    프로그램 내부에서는 이를 모두
    "Cross"라는 하나의 이름으로 통일해서 사용하기 위해
    이 함수를 사용합니다.
    """

    # 문자열이 아니면 라벨로 사용할 수 없습니다.
    if not isinstance(label, str):
        return None

    # 앞뒤 공백을 제거하고 소문자로 변경합니다.
    #
    # 예:
    # " Cross " -> "cross"
    value = label.strip().lower()

    # "+", "cross"는 모두 Cross로 통일합니다.
    if value in ("+", "cross"):
        return "Cross"

    # "x"는 X로 통일합니다.
    if value in ("x",):
        return "X"

    # 위에서 인식하지 못한 값은 알 수 없는 라벨입니다.
    return None


