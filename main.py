# 2. 행렬(Matrix) 검증
# ============================================================

def is_matrix(value: Any) -> bool:
    """
    전달받은 값이 2차원 리스트 형태인지 확인한다.

    --------------------------------------------------------
    정상적인 예
    --------------------------------------------------------

    [
        [1, 2, 3],
        [4, 5, 6],
        [7, 8, 9]
    ]

    --------------------------------------------------------
    잘못된 예
    --------------------------------------------------------

    [1, 2, 3]

    또는

    [
        [1, 2, 3],
        4,
        [7, 8, 9]
    ]

    --------------------------------------------------------
    주의
    --------------------------------------------------------

    이 함수에서는 행의 길이가 같은지까지는 검사하지 않습니다.

    예를 들어:

    [
        [1, 2, 3],
        [4, 5]
    ]

    도 일단 "각 요소가 리스트"이므로
    여기서는 True가 될 수 있습니다.

    행의 길이가 같은지는 다음 함수인
    matrix_size()에서 검사합니다.
    """

    # 먼저 전체 데이터가 list인지 확인합니다.
    #
    # 동시에 비어 있는 리스트인지도 확인합니다.
    #
    # [] -> 행렬로 사용할 수 없으므로 False
    if not isinstance(value, list) or len(value) == 0:
        return False

    # value 안에 들어 있는 모든 요소가 list인지 검사합니다.
    #
    # 예:
    #
    # [
    #     [1, 2],
    #     [3, 4]
    # ]
    #
    # 각 row가 모두 list이므로 True
    #
    # 반면:
    #
    # [
    #     [1, 2],
    #     3
    # ]
    #
    # 두 번째 요소가 list가 아니므로 False
    if not all(isinstance(row, list) for row in value):
        return False

    # 여기까지 통과하면 최소한
    # "리스트 안에 리스트가 들어 있는 형태"입니다.
    return True


def matrix_size(matrix: Any) -> Optional[Tuple[int, int]]:
    """
    행렬의 크기를 반환한다.

    --------------------------------------------------------
    예시
    --------------------------------------------------------

    matrix = [
        [1, 2, 3],
        [4, 5, 6]
    ]

    결과:

    (2, 3)

    즉,

    rows = 2
    cols = 3

    --------------------------------------------------------
    검사 내용
    --------------------------------------------------------

    1. 2차원 리스트인가?
    2. 첫 번째 행에 값이 있는가?
    3. 모든 행의 길이가 같은가?

    위 조건을 만족하면
    (행 개수, 열 개수)를 반환합니다.

    조건을 만족하지 못하면 None을 반환합니다.
    """

    # 먼저 2차원 리스트 형태인지 확인합니다.
    if not is_matrix(matrix):
        return None

    # 행의 개수를 구합니다.
    #
    # 예:
    #
    # [
    #     [1, 2, 3],
    #     [4, 5, 6]
    # ]
    #
    # len(matrix) -> 2
    rows = len(matrix)

    # 첫 번째 행의 길이를 구합니다.
    #
    # 첫 번째 행을 기준으로 열 개수를 정합니다.
    #
    # [1, 2, 3] -> 3
    cols = len(matrix[0])

    # 첫 번째 행이 비어 있으면
    # 열의 개수가 0이므로 정상적인 행렬로 취급하지 않습니다.
    if cols == 0:
        return None

    # 모든 행의 길이가 첫 번째 행의 길이(cols)와
    # 같은지 검사합니다.
    #
    # 예:
    #
    # [
    #     [1, 2, 3],    -> 길이 3
    #     [4, 5, 6],    -> 길이 3
    #     [7, 8, 9]     -> 길이 3
    # ]
    #
    # 모두 같으므로 정상입니다.
    #
    # 반대로:
    #
    # [
    #     [1, 2, 3],    -> 길이 3
    #     [4, 5],       -> 길이 2
    #     [7, 8, 9]     -> 길이 3
    # ]
    #
    # 두 번째 행의 길이가 다르므로 None을 반환합니다.
    #
    # any()는 조건을 만족하는 값이
    # 하나라도 있으면 True입니다.
    #
    # 따라서 이 코드는
    #
    # "길이가 다른 행이 하나라도 있는가?"
    #
    # 를 검사합니다.
    if any(len(row) != cols for row in matrix):
        return None

    # 모든 검사를 통과하면
    # (행 개수, 열 개수)를 반환합니다.
    return rows, cols


def validate_square_matrix(
    matrix: Any,
    expected_size: Optional[int] = None
) -> Tuple[bool, str]:
    """
    정사각형 N×N 행렬인지 검사한다.

    --------------------------------------------------------
    검사 순서
    --------------------------------------------------------

    1. 2차원 리스트인가?
    2. 행 길이가 모두 같은가?
    3. 행 개수와 열 개수가 같은가?
    4. expected_size가 있다면 지정 크기와 같은가?
    5. 모든 값이 숫자로 변환 가능한가?

    모든 조건을 통과하면:

        (True, "")

    실패하면:

        (False, 실패 이유)

    를 반환합니다.
    """

    # 먼저 행렬의 크기를 확인합니다.
    #
    # matrix_size()가 정상적으로 크기를 반환하면
    # 예:
    #
    # (3, 3)
    #
    # 잘못된 행렬이면 None입니다.
    size = matrix_size(matrix)

    # 크기를 알아낼 수 없다면
    # 행렬 자체가 잘못된 것입니다.
    if size is None:
        return False, "2차원 배열이 아니거나 행의 길이가 서로 다릅니다."

    # 튜플을 행 개수와 열 개수로 나눕니다.
    rows, cols = size

    # 정사각형 행렬인지 검사합니다.
    #
    # 3x3 -> 정상
    # 5x5 -> 정상
    # 3x5 -> 잘못됨
    if rows != cols:
        return False, f"정사각형이 아닙니다. 현재 크기: {rows}x{cols}"

    # expected_size가 지정되어 있다면
    # 실제 크기가 정확히 일치하는지도 검사합니다.
    #
    # 예:
    #
    # expected_size = 5
    #
    # 실제 행렬이 5x5 -> 정상
    # 실제 행렬이 3x3 -> 오류
    if expected_size is not None and rows != expected_size:
        return (
            False,
            f"크기 불일치: 기대 크기 {expected_size}x{expected_size}, "
            f"실제 크기 {rows}x{cols}"
        )

    # 행렬 안의 모든 값을 검사합니다.
    #
    # r -> 행 번호
    # c -> 열 번호
    #
    # 각 값이 float으로 변환 가능한지 확인합니다.
    for r, row in enumerate(matrix):
        for c, value in enumerate(row):

            try:

                # 숫자로 변환 가능한지 확인합니다.
                #
                # "1" -> 1.0 가능
                # 1 -> 1.0 가능
                # "abc" -> 변환 불가능
                float(value)

            except (TypeError, ValueError):

                # 숫자로 변환할 수 없는 값이 발견되면
                # 위치와 값을 함께 알려줍니다.
                return (
                    False,
                    f"숫자가 아닌 값 발견: 위치 ({r}, {c}), 값={value!r}"
                )

    # 모든 검사를 통과했습니다.
    return True, ""


def to_float_matrix(matrix: List[List[Any]]) -> List[List[float]]:
    """
    행렬의 모든 값을 float으로 변환한다.

    --------------------------------------------------------
    예시
    --------------------------------------------------------

    입력:

    [
        [1, "2"],
        ["3", 4]
    ]

    출력:

    [
        [1.0, 2.0],
        [3.0, 4.0]
    ]

    --------------------------------------------------------
    왜 필요한가?
    --------------------------------------------------------

    MAC 계산에서는 숫자끼리 곱셈을 해야 합니다.

    따라서 JSON에서 문자열 형태의 숫자가 들어오더라도
    실제 계산 전에 float으로 통일합니다.
    """

    return [
        [float(value) for value in row]
        for row in matrix
    ]


# ============================================================
# 3. MAC 연산
# ============================================================

def mac_score(
    pattern: List[List[float]],
    filter_matrix: List[List[float]]
) -> float:
    """
    패턴과 필터의 MAC 점수를 계산한다.

    MAC =
        Multiply
        +
        Accumulate

    즉, 같은 위치의 값을 곱한 뒤
    계속 더합니다.

    --------------------------------------------------------
    예시
    --------------------------------------------------------

    pattern:

    1 0
    0 1

    filter:

    2 3
    4 5

    계산:

    1×2 + 0×3
    + 0×4 + 1×5

    = 2 + 0 + 0 + 5

    = 7

    --------------------------------------------------------
    시간 복잡도
    --------------------------------------------------------

    N×N 행렬의 모든 위치를 한 번씩 방문하므로

        O(N²)

    입니다.
    """

    # 패턴의 행 개수를 가져옵니다.
    #
    # 정사각형 행렬이므로
    # rows = 열 개수이기도 합니다.
    rows = len(pattern)

    # MAC 결과를 저장할 변수입니다.
    #
    # 처음에는 0입니다.
    score = 0.0

    # 모든 행을 반복합니다.
    for r in range(rows):

        # 모든 열을 반복합니다.
        for c in range(rows):

            # 패턴과 필터의 같은 위치 값을 곱하고
            # 기존 score에 계속 더합니다.
            #
            # 이것이 MAC의 핵심 연산입니다.
            score += pattern[r][c] * filter_matrix[r][c]

    # 최종 MAC 점수를 반환합니다.
    return score


# ============================================================
# 4. 판정(Classification)
# ============================================================
#
# 이 함수는 특정 필터 이름에 종속되지 않습니다.
#
# 따라서 두 모드에서 모두 사용할 수 있습니다.
#
# ------------------------------------------------------------
# 사용자 입력 모드
# ------------------------------------------------------------
#
# classify_scores(
#     score_a,
#     score_b,
#     "A",
#     "B"
# )
#
# 결과:
#
# A
# 또는
# B
# 또는
# UNDECIDED
#
#
# ------------------------------------------------------------
# JSON 모드
# ------------------------------------------------------------
#
# classify_scores(
#     cross_score,
#     x_score,
#     "Cross",
#     "X"
# )
#
# 결과:
#
# Cross
# 또는
# X
# 또는
# UNDECIDED
#
# ============================================================

def classify_scores(
    score_a: float,
    score_b: float,
    label_a: str = "A",
    label_b: str = "B",
    epsilon: float = EPSILON
) -> str:
    """
    두 점수를 비교하여 label_a / label_b / UNDECIDED 중
    하나를 반환한다.

    --------------------------------------------------------
    판정 규칙
    --------------------------------------------------------

    score_a > score_b
        -> label_a

    score_b > score_a
        -> label_b

    두 점수의 차이가 epsilon보다 작으면
        -> UNDECIDED

    --------------------------------------------------------
    예시
    --------------------------------------------------------

    classify_scores(10, 5, "A", "B")
        -> "A"

    classify_scores(5, 10, "A", "B")
        -> "B"

    classify_scores(10, 10, "A", "B")
        -> "UNDECIDED"
    """

    # 두 점수의 차이를 계산합니다.
    #
    # abs()는 절댓값을 구합니다.
    #
    # 예:
    #
    # A = 5
    # B = 10
    #
    # 5 - 10 = -5
    # abs(-5) = 5
    difference = abs(score_a - score_b)

    # 두 점수의 차이가 EPSILON보다 작으면
    # 사실상 동점으로 처리합니다.
    if difference < epsilon:
        return "UNDECIDED"

    # A의 점수가 더 크면 label_a를 반환합니다.
    if score_a > score_b:
        return label_a

    # 여기까지 왔다면
    # score_b가 더 큰 경우입니다.
    return label_b


