# ============================================================
# 핵심 함수의 역할
# ============================================================
#
# ------------------------------------------------------------
# is_matrix()
# ------------------------------------------------------------
#
# "이 데이터가 리스트 안에 리스트가 들어 있는 형태인가?"
# 를 검사합니다.
#
# 예:
#
# [
#     [1, 2],
#     [3, 4]
# ]
#
# -> True
#
#
# ------------------------------------------------------------
# matrix_size()
# ------------------------------------------------------------
#
# "각 행의 길이가 모두 같은가?"
# 를 확인하고
#
# (행 개수, 열 개수)
#
# 를 반환합니다.
#
# 예:
#
# [
#     [1, 2, 3],
#     [4, 5, 6]
# ]
#
# -> (2, 3)
#
#
# ------------------------------------------------------------
# validate_square_matrix()
# ------------------------------------------------------------
#
# "정사각형 N×N이고 모든 값이 숫자인가?"
# 를 최종적으로 검사합니다.
#
#
# ------------------------------------------------------------
# to_float_matrix()
# ------------------------------------------------------------
#
# 행렬의 모든 값을 float으로 통일합니다.
#
#
# ------------------------------------------------------------
# mac_score()
# ------------------------------------------------------------
#
# 패턴과 필터의 같은 위치를 곱하고
# 모두 더합니다.
#
# 이것이 NPU Simulator의 핵심 MAC 연산입니다.
#
#
# ------------------------------------------------------------
# classify_scores()
# ------------------------------------------------------------
#
# 두 MAC 점수를 비교합니다.
#
# A > B
#     -> A
#
# B > A
#     -> B
#
# 거의 동일
#     -> UNDECIDED
#
#
# ------------------------------------------------------------
# measure_mac()
# ------------------------------------------------------------
#
# mac_score()를 여러 번 실행하면서
# 실제 연산 시간을 측정합니다.
#
#
# ------------------------------------------------------------
# run_performance_analysis()
# ------------------------------------------------------------
#
# 3×3
# 5×5
# 13×13
# 25×25
#
# 등의 크기에 대해 Cross와 X의 MAC 연산 시간을 비교합니다.
#
#
# ============================================================
# 사용자 입력 모드의 핵심 흐름
# ============================================================
#
# 사용자 입력
#      │
#      ├───────────────┐
#      │               │
#      ▼               ▼
#   필터 A           필터 B
#      │               │
#      └───────┬───────┘
#              │
#            패턴
#              │
#      ┌───────┴───────┐
#      │               │
#      ▼               ▼
#   mac_score()     mac_score()
#      │               │
#      ▼               ▼
#   A 점수            B 점수
#      │               │
#      └───────┬───────┘
#              │
#              ▼
#     classify_scores()
#              │
#       ┌──────┼──────┐
#       ▼      ▼      ▼
#       A      B   UNDECIDED
#
#
# ============================================================
# JSON 분석 모드의 핵심 흐름
# ============================================================
#
# data.json
#     │
#     ├───────────────┐
#     │               │
#     ▼               ▼
#  filters         patterns
#     │               │
#     ▼               ▼
# 필터 검증        패턴 분석
#     │               │
#     │        ┌──────┴──────┐
#     │        │             │
#     │        ▼             ▼
#     │      Cross           X
#     │       필터           필터
#     │        │             │
#     │        ▼             ▼
#     │   Cross 점수       X 점수
#     │        │             │
#     │        └──────┬──────┘
#     │               │
#     │               ▼
#     │       classify_scores()
#     │               │
#     │        ┌──────┼──────┐
#     │        ▼      ▼      ▼
#     │      Cross     X   UNDECIDED
#     │               │
#     │               ▼
#     │          expected와 비교
#     │               │
#     │        ┌──────┴──────┐
#     │        ▼             ▼
#     │      PASS           FAIL
#     │
#     └───────────────┐
#                     ▼
#            성능 분석 실행
#
#
# ============================================================
# 성능 측정 구조
