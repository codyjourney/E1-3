# 10. 성능 분석
# ============================================================

def run_performance_analysis(
    sizes: Tuple[int, ...],
    repeats: int = PERFORMANCE_REPEATS
) -> None:
    """
    지정된 행렬 크기에 대해
    Cross/X 필터의 MAC 성능을 각각 측정한다.

    --------------------------------------------------------
    예:
    --------------------------------------------------------

    run_performance_analysis(
        (3, 5, 13, 25),
        10
    )

    결과:

    3x3   -> Cross/X 시간
    5x5   -> Cross/X 시간
    13x13 -> Cross/X 시간
    25x25 -> Cross/X 시간

    --------------------------------------------------------
    중요한 점
    --------------------------------------------------------

    실제 성능 측정에서 사용하는 것은
    create_performance_pattern(),
    create_cross_filter(),
    create_x_filter()에서 만든 데이터입니다.

    실제 JSON 패턴을 사용하는 것이 아니라
    동일한 조건에서 행렬 크기에 따른 MAC 연산 시간을
    비교하기 위한 테스트입니다.
    """

    print("\n#---------------------------------------")
    print(f"# [성능 분석] 평균/{repeats}회")
    print("#---------------------------------------")

    # 성능 결과 표의 제목을 출력합니다.
    print(
        f"{'크기':<12}"
        f"{'Cross(ms)':>15}"
        f"{'X(ms)':>15}"
        f"{'MAC 횟수(N²)':>18}"
    )

    print("-" * 60)

    # 전달받은 각각의 크기에 대해 반복합니다.
    for size in sizes:

        # ----------------------------------------------------
        # 1. 성능 측정용 패턴 생성
        # ----------------------------------------------------

        pattern = create_performance_pattern(size)

        # ----------------------------------------------------
        # 2. Cross 필터 생성
        # ----------------------------------------------------

        cross_filter = create_cross_filter(size)

        # ----------------------------------------------------
        # 3. X 필터 생성
        # ----------------------------------------------------

        x_filter = create_x_filter(size)

        # ----------------------------------------------------
        # 4. Cross MAC 성능 측정
        # ----------------------------------------------------

        cross_ms, cross_score = measure_mac(
            pattern,
            cross_filter,
            repeats
        )

        # ----------------------------------------------------
        # 5. X MAC 성능 측정
        # ----------------------------------------------------

        x_ms, x_score = measure_mac(
            pattern,
            x_filter,
            repeats
        )

        # ----------------------------------------------------
        # 6. MAC 기본 연산 횟수
        # ----------------------------------------------------
        #
        # N×N 행렬의 모든 위치를 한 번씩 계산하므로
        #
        # N²
        #
        # 개의 곱셈/누적 위치가 발생합니다.

        operation_count = size * size

        # 결과를 표 형태로 출력합니다.
        print(
            f"{size}x{size:<8}"
            f"{cross_ms:>15.6f}"
            f"{x_ms:>15.6f}"
            f"{operation_count:>18}"
        )


