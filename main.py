def run_json_mode(
    json_path: str = "data.json"
) -> None:
    """
    data.json을 읽어 모든 패턴 케이스를 분석한다.

    --------------------------------------------------------
    전체 흐름
    --------------------------------------------------------

    JSON 파일
       ↓
    load_json_file()
       ↓
    filters / patterns 분리
       ↓
    필터 검사
       ↓
    각 패턴 분석
       ↓
    PASS / FAIL 집계
       ↓
    성능 분석
       ↓
    최종 결과 출력
    """

    # --------------------------------------------------------
    # [1] JSON 데이터 로드
    # --------------------------------------------------------

    print("\n#---------------------------------------")
    print("# [1] JSON 데이터 로드")
    print("#---------------------------------------")

    # 지정된 JSON 파일이 실제로 존재하는지 확인합니다.
    if not os.path.exists(json_path):
        print(
            f"파일을 찾을 수 없습니다: {json_path}"
        )
        return

    try:

        # JSON 파일을 읽습니다.
        data = load_json_file(json_path)

    # JSON 문법이 잘못된 경우입니다.
    except json.JSONDecodeError as error:

        print("JSON 파싱 오류:")
        print(error)
        return

    # 파일을 읽는 과정에서 문제가 발생한 경우입니다.
    except OSError as error:

        print("파일 읽기 오류:")
        print(error)
        return

    # JSON 최상위 구조가 dictionary인지 확인합니다.
    if not isinstance(data, dict):
        print(
            "스키마 오류: "
            "최상위 JSON은 객체여야 합니다."
        )
        return

    # filters와 patterns를 가져옵니다.
    filters = data.get("filters")
    patterns = data.get("patterns")

    # filters가 dictionary인지 확인합니다.
    if not isinstance(filters, dict):
        print(
            "스키마 오류: 'filters'가 없습니다."
        )
        return

    # patterns가 dictionary인지 확인합니다.
    if not isinstance(patterns, dict):
        print(
            "스키마 오류: 'patterns'가 없습니다."
        )
        return

    # --------------------------------------------------------
    # [2] 필터 로드
    # --------------------------------------------------------

    print("\n#---------------------------------------")
    print("# [2] 필터 로드")
    print("#---------------------------------------")

    # 정상적으로 로드된 필터 크기를 저장합니다.
    #
    # 현재 코드에서는 저장 후 직접 사용하지 않지만,
    # 어떤 크기의 필터가 정상적으로 로드되었는지
    # 관리할 수 있도록 만든 변수입니다.
    valid_filter_sizes = []

    # 지원하는 크기를 하나씩 검사합니다.
    for size in SUPPORTED_JSON_SIZES:

        # 해당 크기의 Cross/X 필터를 검사합니다.
        ok, reason, normalized_filters = (
            validate_filter_group(
                filters,
                size
            )
        )

        if ok:

            # 정상적으로 로드된 크기를 기록합니다.
            valid_filter_sizes.append(size)

            print(
                f"✓ size_{size:<2} "
                f"필터 로드 완료 (Cross, X)"
            )

        else:

            # 필터가 잘못된 경우 오류 이유를 출력합니다.
            print(
                f"✗ size_{size:<2} "
                f"필터 로드 실패: {reason}"
            )

    # --------------------------------------------------------
    # [3] 패턴 분석
    # --------------------------------------------------------

    print("\n#---------------------------------------")
    print("# [3] 패턴 분석 (라벨 정규화 적용)")
    print("#---------------------------------------")

    # 전체 테스트 개수
    total = 0

    # PASS 개수
    passed = 0

    # FAIL 개수
    failed = 0

    # 실패한 케이스의 상세 정보를 저장합니다.
    failures = []

    # patterns 안에 있는 모든 케이스를 하나씩 분석합니다.
    for case_id, case_data in patterns.items():

        # 전체 테스트 수 증가
        total += 1

        # 하나의 패턴 케이스를 분석합니다.
        result = analyze_pattern_case(
            case_id,
            case_data,
            filters
        )

        # PASS이면 passed 증가
        if result["status"] == "PASS":

            passed += 1

        else:

            # FAIL이면 failed 증가
            failed += 1

            # 실패 케이스의 상세 정보를 저장합니다.
            failures.append(result)

        # 현재 케이스의 이름을 출력합니다.
        print(f"\n--- {case_id} ---")

        # MAC 점수가 정상적으로 계산된 경우
        # Cross/X 점수를 출력합니다.
        if result["cross_score"] is not None:

            print(
                f"Cross 점수: "
                f"{result['cross_score']:.10f}"
            )

            print(
                f"X 점수: "
                f"{result['x_score']:.10f}"
            )

            # 실제 판정과 expected를 함께 출력합니다.
            print(
                f"판정: {result['prediction']} | "
                f"expected: {result['expected']} | "
                f"{result['status']}"
            )

            # FAIL인 경우 원인도 출력합니다.
            if result["status"] == "FAIL":

                print(
                    f"원인: {result['reason']}"
                )

        else:

            # MAC 계산 전에 오류가 발생한 경우
            # 점수가 없으므로 오류 원인만 출력합니다.
            print(
                f"판정: FAIL | "
                f"원인: {result['reason']}"
            )

    # --------------------------------------------------------
    # [4] 성능 분석
    # --------------------------------------------------------

    print("\n#---------------------------------------")
    print("# [4] 성능 분석")
    print("#---------------------------------------")

    # 3x3, 5x5, 13x13, 25x25에 대해
    # Cross/X MAC 성능을 측정합니다.
    run_performance_analysis(
        (3, 5, 13, 25),
        PERFORMANCE_REPEATS
    )

    # --------------------------------------------------------
    # [5] 결과 요약
    # --------------------------------------------------------

    print("\n#---------------------------------------")
    print("# [5] 결과 요약")
    print("#---------------------------------------")

    # 전체 테스트 개수를 출력합니다.
    print(f"총 테스트: {total}개")

    # PASS 개수를 출력합니다.
    print(f"통과: {passed}개")

    # FAIL 개수를 출력합니다.
    print(f"실패: {failed}개")

    # 실패 케이스가 있는 경우
    if failures:

        print("\n실패 케이스:")

        # 실패한 모든 케이스를 출력합니다.
        for failure in failures:

            print(
                f"- {failure['case_id']}: "
                f"{failure['reason']}"
            )

    else:

        # 실패가 하나도 없으면 이 메시지를 출력합니다.
        print("\n실패 케이스가 없습니다.")


