def load_json_file(path: str) -> Dict[str, Any]:
    """
    JSON 파일을 읽어 Python 객체로 변환한다.

    --------------------------------------------------------
    예:
    --------------------------------------------------------

    path = "data.json"

    open()
        ↓
    json.load()
        ↓
    Python dict
    """

    # UTF-8 인코딩으로 JSON 파일을 엽니다.
    with open(path, "r", encoding="utf-8") as file:

        # JSON 데이터를 Python 객체로 변환합니다.
        return json.load(file)


def extract_size_from_pattern_key(
    key: str
) -> Optional[int]:
    """
    패턴 키에서 행렬 크기 N을 추출한다.

    --------------------------------------------------------
    기대하는 형식
    --------------------------------------------------------

    size_{N}_{idx}

    예:

    size_5_0
        -> 5

    size_13_3
        -> 13

    size_25_10
        -> 25

    --------------------------------------------------------
    형식이 잘못되면
    --------------------------------------------------------

    None을 반환한다.
    """

    # 정규표현식으로 키의 형식을 검사합니다.
    #
    # (\d+)
    #     -> 숫자가 하나 이상
    #
    # 첫 번째 숫자 그룹:
    #     행렬 크기
    #
    # 두 번째 숫자 그룹:
    #     패턴 인덱스
    match = re.fullmatch(
        r"size_(\d+)_(\d+)",
        key
    )

    # 형식이 맞지 않으면 None
    if not match:
        return None

    # 첫 번째 그룹을 정수로 변환합니다.
    return int(match.group(1))


# ============================================================
# 13. JSON 필터 검증
# ============================================================

def validate_filter_group(
    filters: Any,
    size: int
) -> Tuple[
    bool,
    str,
    Optional[Dict[str, List[List[float]]]]
]:
    """
    size_N 필터 그룹의 스키마와 행렬 크기를 검사한다.

    --------------------------------------------------------
    기대하는 JSON 구조 예
    --------------------------------------------------------

    "filters": {
        "size_5": {
            "cross": [...],
            "x": [...]
        }
    }

    --------------------------------------------------------
    반환값
    --------------------------------------------------------

    정상:

    (
        True,
        "",
        {
            "Cross": [...],
            "X": [...]
        }
    )

    오류:

    (
        False,
        "오류 메시지",
        None
    )
    """

    # filters 전체가 dict인지 확인합니다.
    if not isinstance(filters, dict):
        return (
            False,
            "filters가 객체가 아닙니다.",
            None
        )

    # 검사하려는 크기의 key를 만듭니다.
    #
    # size = 5
    # ->
    # "size_5"
    size_key = f"size_{size}"

    # 해당 크기의 필터가 존재하는지 확인합니다.
    if size_key not in filters:
        return (
            False,
            f"{size_key} 필터가 존재하지 않습니다.",
            None
        )

    # size_N에 해당하는 데이터를 가져옵니다.
    group = filters[size_key]

    # size_N의 값 역시 객체(dict)여야 합니다.
    if not isinstance(group, dict):
        return (
            False,
            f"{size_key} 값이 객체가 아닙니다.",
            None
        )

    # 검증을 통과한 필터를
    # 표준 라벨로 저장할 dictionary입니다.
    normalized = {}

    # JSON에서는 cross와 x를 검사합니다.
    for raw_label in ("cross", "x"):

        # 해당 필터가 존재하는지 확인합니다.
        if raw_label not in group:
            return (
                False,
                f"{size_key}에 '{raw_label}' 필터가 없습니다.",
                None
            )

        # cross -> Cross
        # x -> X
        #
        # 라벨을 프로그램 내부 표준 이름으로 변경합니다.
        label = normalize_label(raw_label)

        # 실제 행렬을 가져옵니다.
        matrix = group[raw_label]

        # 행렬이 정확히 size x size인지 검사합니다.
        ok, reason = validate_square_matrix(
            matrix,
            expected_size=size
        )

        # 행렬 검증에 실패하면 오류를 반환합니다.
        if not ok:
            return (
                False,
                f"{size_key}/{raw_label}: {reason}",
                None
            )

        # 정상적인 행렬은 모든 값을 float으로 변환합니다.
        #
        # 예:
        #
        # "1" -> 1.0
        normalized[label] = to_float_matrix(matrix)

    # 검증된 Cross/X 필터를 반환합니다.
    return True, "", normalized


